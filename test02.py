print('A diferença entre um número e seu dobro é 20. Qual é esse número?')
# A diferença entre um número e seu dobro é 20.
# x - 2x = 20
# -x = 20
# x = -20

x = -20
dobro_de_x = x*2
resultado = x - dobro_de_x

print(f"O número é {x}.")
print(f"Sua terça parte é {dobro_de_x}.")
print(f"A diferença entre {x} e {dobro_de_x} é {resultado}.")
